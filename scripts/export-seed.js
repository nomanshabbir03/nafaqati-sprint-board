// Turns the local SQLite board (data/board.db) into supabase/seed.sql so existing cards move to Supabase.
// Run once: node scripts/export-seed.js
const fs = require('fs');
const path = require('path');
const { DatabaseSync } = require('node:sqlite');

const src = path.join(__dirname, '..', 'data', 'board.db');
if (!fs.existsSync(src)) { console.error('No data/board.db found.'); process.exit(1); }
const db = new DatabaseSync(src, { readOnly: true });

const q = (v) => (v == null ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const settings = Object.fromEntries(db.prepare('SELECT key, value FROM settings').all().map((r) => [r.key, r.value]));
const tasks = db.prepare('SELECT * FROM tasks ORDER BY position, id').all();

let sql = '-- Generated by scripts/export-seed.js. Run after schema.sql, on an empty tasks table.\n';
const off = String(settings.offDays || '0').split(',').filter((x) => x !== '').map(Number);
sql += `insert into public.board_settings (id, title, subtitle, range_start, range_end, off_days) values (1, ${q(settings.title || 'Sprint Board')}, ${q(settings.subtitle || '')}, ${q(settings.rangeStart || '2026-10-23')}, ${q(settings.rangeEnd || '2026-10-29')}, '{${off.join(',')}}')\n`;
sql += 'on conflict (id) do update set title = excluded.title, subtitle = excluded.subtitle, range_start = excluded.range_start, range_end = excluded.range_end, off_days = excluded.off_days;\n\n';
if (tasks.length) {
  sql += 'insert into public.tasks (title, notes, status, area, priority, start_date, end_date, assignee, position) values\n';
  sql += tasks.map((t) => `  (${q(t.title)}, ${q(t.notes)}, ${q(t.status)}, ${q(t.area)}, ${q(t.priority)}, ${q(t.start)}, ${q(t.end)}, ${q(t.assignee)}, ${t.position})`).join(',\n') + ';\n';
}
fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'seed.sql'), sql);
console.log(`Wrote supabase/seed.sql with ${tasks.length} cards.`);
